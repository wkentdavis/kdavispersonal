-- SAR Q9 loads to Home ncmfp_prod.SAR_RPTAGEMSR  REINSTS 
-- Count of Stays (REINSTS) by duration and age group

-- Assume Q2 2025 to test
-- 1 get ED visits and hospitalizations from incident log  MFPTracker_CriticalIncidents
-- Working but may need to coalesce hospital days and shorten time frame (or link to calendar for SFY, CY, Q, M, SEMI)
-- Need to pull down SAR to confirm the numbers

SET @StartMonth = '2026-01-01';
SET @EndMonth   = '2026-06-01';

WITH Q9int AS (
 SELECT
       AGE_WHEN_TRANSITIONED `Age Upon Transition`,
       CASE WHEN AGE_WHEN_TRANSITIONED  BETWEEN 18 AND 64 THEN '18 - 64' 
       WHEN AGE_WHEN_TRANSITIONED  BETWEEN 65 AND 74 THEN '65 - 74' 
       WHEN AGE_WHEN_TRANSITIONED  BETWEEN 75 AND 84 THEN '75 - 84' 
       WHEN AGE_WHEN_TRANSITIONED  >= 85 THEN '85+' 
       ELSE NULL END AS AGE_GROUP,
       DAYS_IN_HOSPITAL,
       CASE WHEN DAYS_IN_HOSPITAL  BETWEEN 1 AND 20 THEN 'SHORT TERM 20 DAYS OR LESS' 
       WHEN DAYS_IN_HOSPITAL  BETWEEN 21 AND 100 THEN 'MEDIUM TERM 21-100 DAYS' 
       WHEN DAYS_IN_HOSPITAL > 100 THEN 'LONG TERM OVER 100 DAYS' 
       ELSE NULL END AS STAY_CATEGORY,
       INCIDENT_TYPE `Nature of Critical Incident`,
       CRITICAL_INCIDENT_DATE,
       concat(Cal.Month_Name_Short,Cal.Calendar_Year) as ReportMonth,
       concat(Cal.Calendar_Year,' ',Cal.Semi_Annual_Period) SARPeriod
    FROM data_mart.mfp_tracker_critical_incidents CI
    INNER JOIN reference.calendar Cal 
        ON CI.CRITICAL_INCIDENT_DATE = Cal.Calendar_Date
    WHERE INCIDENT_TYPE IN ('Emergency Room Visit', 'Hospitalization')
	AND Cal.Month_First_Date BETWEEN @StartMonth AND @EndMonth
      AND LATEST_EXTRACT = 1
      )
    SELECT
		SARPeriod,
        ReportMonth,
		STAY_CATEGORY, 
        COUNT(CASE WHEN AGE_GROUP = '18 - 64' THEN CRITICAL_INCIDENT_DATE END) AS AGE18_64,
        COUNT(CASE WHEN AGE_GROUP = '65 - 74'  THEN CRITICAL_INCIDENT_DATE END) AS AGE65_74,
        COUNT(CASE WHEN AGE_GROUP = '75 - 84' THEN CRITICAL_INCIDENT_DATE END) AS AGE75_84,
        COUNT(CASE WHEN AGE_GROUP = '85+' THEN CRITICAL_INCIDENT_DATE END) AS AGE85PLUS,
        COUNT(CRITICAL_INCIDENT_DATE) as TOTAL
    FROM Q9int 
    WHERE DAYS_IN_HOSPITAL > 0 -- B/C THERE ARE 2 RECORDS WITH NEGATIVE DAYS
    GROUP BY 1,2,3 ORDER BY 1 desc;
-- SOME DISCEPANCY IN AGE 65-74 VS 75-84 THE 2 FILES ARE SWAPPED.

