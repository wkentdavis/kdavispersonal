/* ----------------------------------------------------------------
   10. REGION ROLLUP VS ALL
   Because participants should normally belong to one region, the SUM of
   region NUM/DEN should equal ALL NUM/DEN. Rows returned need review.
   Note: FIRSTCALL uses REGION_ASSIGNED as its STRAT label in source code.
   ---------------------------------------------------------------- */
WITH all_rows AS (
    SELECT EXTRACTDT, YYYYMM, UPPER(MSR) MSR, NUM, DEN
    FROM data_mart.VayaSLA_Measures
    WHERE EXTRACTDT=@extractdt AND STRAT='ALL'
),
region_rows AS (
    SELECT EXTRACTDT, YYYYMM, UPPER(MSR) MSR,
           SUM(NUM) REGION_NUM,
           SUM(DEN) REGION_DEN
    FROM data_mart.VayaSLA_Measures
    WHERE EXTRACTDT=@extractdt
      AND UPPER(STRAT) IN ('REGION','REGION_ASSIGNED')
    GROUP BY EXTRACTDT, YYYYMM, UPPER(MSR)
)
SELECT
    a.EXTRACTDT, a.YYYYMM, a.MSR,
    a.NUM ALL_NUM, r.REGION_NUM,
    a.DEN ALL_DEN, r.REGION_DEN,
    CASE
       WHEN r.MSR IS NULL THEN 'MISSING REGION OUTPUT'
       WHEN a.NUM <> r.REGION_NUM THEN 'NUM DOES NOT ROLL UP'
       WHEN a.DEN <> r.REGION_DEN THEN 'DEN DOES NOT ROLL UP'
    END QA_ISSUE
FROM all_rows a
LEFT JOIN region_rows r
  ON r.EXTRACTDT=a.EXTRACTDT
 AND r.YYYYMM <=> a.YYYYMM
 AND r.MSR=a.MSR
WHERE r.MSR IS NULL
   OR a.NUM <> r.REGION_NUM
   OR a.DEN <> r.REGION_DEN
ORDER BY a.MSR, a.YYYYMM;

