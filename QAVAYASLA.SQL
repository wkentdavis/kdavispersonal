    o.NUM AS OUTPUT_NUM,
    e.DEN AS EXPECTED_DEN,
    o.DEN AS OUTPUT_DEN,
    CASE WHEN e.DEN=0 THEN NULL ELSE e.NUM/e.DEN END AS EXPECTED_VAL,
