        WHEN e.DEN <> o.DEN THEN 'FAIL - DEN'
        WHEN e.DEN = 0 AND o.VAL IS NOT NULL THEN 'FAIL - VAL SHOULD BE NULL'
        WHEN e.DEN > 0 AND ABS((e.NUM/e.DEN)-o.VAL) > 0.0000001 THEN 'FAIL - VAL'
        ELSE 'PASS'
    END AS QA_RESULT
