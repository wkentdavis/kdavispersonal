/* ================================================================
   VAYA SLA MEASURES - QA / VALIDATION SCRIPT
   Purpose:
     1. Inventory measure output
     2. Find duplicate / malformed output rows
     3. Validate NUM, DEN, and VAL relationships
     4. Confirm expected stratifications exist
     5. Recalculate each ALL-level measure from source data and compare
        the expected result to the stored output

   Notes:
     - Main measures are stored in data_mart.VayaSLA_Measures.
     - CI_DEPT_REPORTED_DT_MET is stored in data_mart.VayaSLA_Measures
       in the supplied production script.
     - UPPER(MSR) is used in QA to catch capitalization inconsistencies.
   ================================================================ */

/* ----------------------------------------------------------------
   0. Select extract date to validate
   ---------------------------------------------------------------- */
SET @extractdt = (SELECT MAX(EXTRACTDT) FROM measures.VayaSLA_Measures);
SET @ci_extractdt = (SELECT MAX(EXTRACTDT) FROM measures.VayaSLA_Measures
                     WHERE UPPER(MSR) = 'CI_DEPT_REPORTED_DT_MET');

SELECT @extractdt AS MAIN_EXTRACTDT_TO_TEST,
       @ci_extractdt AS CI_EXTRACTDT_TO_TEST;

/* ----------------------------------------------------------------
   1. INVENTORY - what measures and stratifications were produced?
   Expected for most measures:
       ALL
       REGION (FIRSTCALL currently uses REGION_ASSIGNED)
       TRANSITION COORDINATOR
   ---------------------------------------------------------------- */
SELECT
    UPPER(MSR) AS MSR_NORMALIZED,
    STRAT,
    COUNT(*) AS OUTPUT_ROWS,
    MIN(YYYYMM) AS FIRST_YYYYMM,
    MAX(YYYYMM) AS LAST_YYYYMM,
    SUM(NUM) AS SUM_NUM,
    SUM(DEN) AS SUM_DEN
FROM measures.VayaSLA_Measures
WHERE EXTRACTDT = @extractdt
GROUP BY UPPER(MSR), STRAT
ORDER BY UPPER(MSR), STRAT;

/* Critical incident inventory */
SELECT
    UPPER(MSR) AS MSR_NORMALIZED,
    STRAT,
    COUNT(*) AS OUTPUT_ROWS,
    MIN(YYYYMM) AS FIRST_YYYYMM,
    MAX(YYYYMM) AS LAST_YYYYMM,
    SUM(NUM) AS SUM_NUM,
    SUM(DEN) AS SUM_DEN
FROM measures.VayaSLA_Measures
WHERE EXTRACTDT = @ci_extractdt
  AND UPPER(MSR) = 'CI_DEPT_REPORTED_DT_MET'
GROUP BY UPPER(MSR), STRAT
ORDER BY STRAT;

/* ----------------------------------------------------------------
   2. MEASURE NAME CONSISTENCY
   Returns normalized measure names that appear with >1 spelling/case.
   Ideally returns zero rows.
   ---------------------------------------------------------------- */
SELECT
    UPPER(MSR) AS MSR_NORMALIZED,
    COUNT(DISTINCT BINARY MSR) AS DISTINCT_SPELLINGS,
    GROUP_CONCAT(DISTINCT BINARY MSR ORDER BY MSR SEPARATOR ' | ') AS SPELLINGS
FROM measures.VayaSLA_Measures
WHERE EXTRACTDT = @extractdt
GROUP BY UPPER(MSR)
HAVING COUNT(DISTINCT BINARY MSR) > 1;

/* ----------------------------------------------------------------
   3. DUPLICATE OUTPUT KEYS
   There should normally be one row per:
   EXTRACTDT + YYYYMM + MSR + STRAT + STRATVAL.
   Ideally returns zero rows.
   ---------------------------------------------------------------- */
SELECT
    EXTRACTDT,
    YYYYMM,
    UPPER(MSR) AS MSR,
    STRAT,
    STRATVAL,
    COUNT(*) AS DUPLICATE_COUNT
FROM measures.VayaSLA_Measures
WHERE EXTRACTDT = @extractdt
GROUP BY EXTRACTDT, YYYYMM, UPPER(MSR), STRAT, STRATVAL
HAVING COUNT(*) > 1
ORDER BY MSR, YYYYMM, STRAT, STRATVAL;

/* ----------------------------------------------------------------
   4. INVALID NUMERATOR / DENOMINATOR / VALUE
   Ideally returns zero rows.
   ---------------------------------------------------------------- */
SELECT
    EXTRACTDT,
    YYYYMM,
    MSR,
    STRAT,
    STRATVAL,
    NUM,
    DEN,
    VAL,
    CASE
        WHEN NUM < 0 THEN 'NUM < 0'
        WHEN DEN < 0 THEN 'DEN < 0'
        WHEN NUM > DEN THEN 'NUM > DEN'
        WHEN DEN = 0 AND VAL IS NOT NULL THEN 'DEN = 0 but VAL is populated'
        WHEN DEN > 0 AND VAL IS NULL THEN 'DEN > 0 but VAL is NULL'
        WHEN VAL < 0 OR VAL > 1 THEN 'VAL outside 0-1 range'
        WHEN DEN > 0 AND ABS(VAL - (NUM / DEN)) > 0.0000001 THEN 'VAL does not equal NUM / DEN'
        ELSE 'UNKNOWN'
    END AS QA_ISSUE
FROM measures.VayaSLA_Measures
WHERE EXTRACTDT = @extractdt
  AND (
       NUM < 0
       OR DEN < 0
       OR NUM > DEN
       OR (DEN = 0 AND VAL IS NOT NULL)
       OR (DEN > 0 AND VAL IS NULL)
       OR VAL < 0
       OR VAL > 1
       OR (DEN > 0 AND ABS(VAL - (NUM / DEN)) > 0.0000001)
  )
ORDER BY MSR, YYYYMM, STRAT, STRATVAL;

/* Same mathematical check for CI measure */
SELECT
    EXTRACTDT, YYYYMM, MSR, STRAT, STRATVAL, NUM, DEN, VAL,
    CASE
        WHEN NUM < 0 THEN 'NUM < 0'
        WHEN DEN < 0 THEN 'DEN < 0'
        WHEN NUM > DEN THEN 'NUM > DEN'
        WHEN DEN = 0 AND VAL IS NOT NULL THEN 'DEN = 0 but VAL is populated'
        WHEN DEN > 0 AND VAL IS NULL THEN 'DEN > 0 but VAL is NULL'
        WHEN VAL < 0 OR VAL > 1 THEN 'VAL outside 0-1 range'
        WHEN DEN > 0 AND ABS(VAL - (NUM / DEN)) > 0.0000001 THEN 'VAL does not equal NUM / DEN'
        ELSE 'UNKNOWN'
    END AS QA_ISSUE
FROM measures.VayaSLA_Measures
WHERE EXTRACTDT = @ci_extractdt
  AND UPPER(MSR) = 'CI_DEPT_REPORTED_DT_MET'
  AND (
       NUM < 0 OR DEN < 0 OR NUM > DEN
       OR (DEN = 0 AND VAL IS NOT NULL)
       OR (DEN > 0 AND VAL IS NULL)
       OR VAL < 0 OR VAL > 1
       OR (DEN > 0 AND ABS(VAL - (NUM / DEN)) > 0.0000001)
  );

/* ----------------------------------------------------------------
   5. STRAT / STRATVAL CONSISTENCY
   ALL should have NULL STRATVAL.
   REGION and TRANSITION COORDINATOR should normally have STRATVAL.
   ---------------------------------------------------------------- */
SELECT *,
       CASE
           WHEN STRAT = 'ALL' AND STRATVAL IS NOT NULL
               THEN 'ALL row has STRATVAL'
           WHEN STRAT <> 'ALL' AND STRATVAL IS NULL
               THEN 'Stratified row has NULL STRATVAL'
       END AS QA_ISSUE
FROM measures.VayaSLA_Measures
WHERE EXTRACTDT = @extractdt
  AND ((STRAT = 'ALL' AND STRATVAL IS NOT NULL)
       OR (STRAT <> 'ALL' AND STRATVAL IS NULL))
ORDER BY MSR, YYYYMM, STRAT;

/* ----------------------------------------------------------------
   6. EXPECTED STRATIFICATIONS BY MEASURE
   Normalizes REGION_ASSIGNED to REGION for this test.
   Each main measure should normally have all 3 stratification types.
   Ideally returns zero rows.
   ---------------------------------------------------------------- */
WITH measure_strats AS (
    SELECT DISTINCT
        UPPER(MSR) AS MSR,
        CASE WHEN UPPER(STRAT) = 'REGION_ASSIGNED' THEN 'REGION'
             ELSE UPPER(STRAT)
        END AS STRAT_NORM
    FROM measures.VayaSLA_Measures
    WHERE EXTRACTDT = @extractdt
),
expected AS (
    SELECT 'ALL' AS STRAT_NORM
    UNION ALL SELECT 'REGION'
    UNION ALL SELECT 'TRANSITION COORDINATOR'
),
measures AS (
    SELECT DISTINCT MSR FROM measure_strats
)
SELECT m.MSR,
       e.STRAT_NORM AS MISSING_STRATIFICATION
FROM measures m
CROSS JOIN expected e
LEFT JOIN measure_strats s
       ON s.MSR = m.MSR
      AND s.STRAT_NORM = e.STRAT_NORM
WHERE s.MSR IS NULL
ORDER BY m.MSR, e.STRAT_NORM;

